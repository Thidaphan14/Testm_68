print("=== โปรแกรมคำนวณพื้นที่รูปทรงเรขาคณิต ===")
print("1. สี่เหลี่ยมมุมฉาก")
print("2. วงกลม")
print("3. สามเหลี่ยม")

เลือก = input("เลือกรูปทรง (1/2/3): ")

if เลือก == "1":
    กว้าง = float(input("กรอกความกว้าง: "))
    ยาว = float(input("กรอกความยาว: "))
    พื้นที่ = กว้าง * ยาว
    เส้นรอบรูป = 2 * (กว้าง + ยาว)
    print(f"พื้นที่ = {พื้นที่} ตารางหน่วย")
    print(f"เส้นรอบรูป = {เส้นรอบรูป} หน่วย")

elif เลือก == "2":
    รัศมี = float(input("กรอกรัศมี: "))
    พื้นที่ = math.pi * รัศมี ** 2
    เส้นรอบวง = 2 * math.pi * รัศมี
    print(f"พื้นที่ = {พื้นที่:.2f} ตารางหน่วย")
    print(f"เส้นรอบวง = {เส้นรอบวง:.2f} หน่วย")

elif เลือก == "3":
    ฐาน = float(input("กรอกความยาวฐาน: "))
    สูง = float(input("กรอกความสูง: "))
    พื้นที่ = 0.5 * ฐาน * สูง
    print(f"พื้นที่ = {พื้นที่} ตารางหน่วย")

else:
    print("กรุณาเลือก 1, 2 หรือ 3 เท่านั้น")

